"""
Model cards and Hugging Face Hub uploads for merged models::

    from MixtureKit.hub import write_model_card, push_to_hub

    write_model_card("models_merge/gemmax")                  # README.md next to the weights
    push_to_hub("models_merge/gemmax", "my-org/gemmax-3x4b")  # card + upload
"""

import glob
import json
import os

import yaml
from safetensors import safe_open

REPOSITORY = "https://github.com/MBZUAI-Paris/MixtureKit"
CITATION = """@article{chamma2025mixturekit,
  title={MixtureKit: A General Framework for Composing, Training, and Visualizing Mixture-of-Experts Models},
  author={Chamma, Ahmad and Herraoui, Omar El and Shang, Guokan},
  journal={arXiv preprint arXiv:2512.12121},
  year={2025}
}"""

METHODS = {
    "btx": ("Branch-Train-MiX (BTX)", "the selected projections of every expert are kept, each with its own top-{k} router; the other weights are averaged"),
    "traditional": ("Mixtral-style MoE", "the feed-forward blocks of the experts are kept, behind one top-{k} router per layer; the other weights are averaged"),
    "bts": ("Branch-Train-Stitch (BTS)", "the experts run in parallel next to the hub, every expert intact, joined by stitch layers"),
}


def _stored_keys(model_dir):
    keys = set()
    for file in glob.glob(os.path.join(model_dir, "*.safetensors")):
        with safe_open(file, framework="pt") as handle:
            keys.update(handle.keys())
    return keys


MARKER = "<!-- generated by MixtureKit -->"


def _is_hub_id(model_id):
    return "/" in model_id and not os.path.exists(model_id) and not model_id.startswith((".", "/", "~"))


def _cell(text):
    """Text for a Markdown table cell."""
    return str(text).replace("|", "\\|").replace("\r", " ").replace("\n", " ")


def _redacted(build, is_local):
    """The build configuration without the local paths of the experts (private)."""
    build = json.loads(json.dumps(build))
    for expert, local in zip(build.get("experts", []), is_local):
        if local:
            expert["model_id"] = f"<local: {os.path.basename(os.path.normpath(expert['model_id']))}>"
    return build


def model_card(model_dir, repo_id=None):
    """
    This function returns the model card of a merged model, in Markdown: the experts, the
    method, whether the routers are trained, how to load and inspect it, the configuration
    to rebuild it and the citation.

    Parameters
    ----------
    model_dir: str
        The directory of the merged model.
    repo_id: str, default=None
        Its Hub id, used in the snippets (the directory otherwise).
    """
    config_file = os.path.join(model_dir, "config.json")
    if not os.path.exists(config_file):
        if os.path.exists(os.path.join(model_dir, "adapter_config.json")):
            raise ValueError(
                f"{model_dir} holds LoRA adapters: merge them first, e.g. "
                "PeftModel.from_pretrained(model, dir).merge_and_unload().save_pretrained(out)"
            )
        raise ValueError(f"{model_dir} is not a model directory (no config.json)")
    with open(config_file, encoding="utf-8") as f:
        config = json.load(f)
    method = config.get("moe_method")
    if method not in METHODS:
        raise ValueError(f"{model_dir} is not a model merged with MixtureKit")
    build_file = os.path.join(model_dir, "mixturekit_config.json")
    build = json.load(open(build_file, encoding="utf-8")) if os.path.exists(build_file) else None

    model_ids = config.get("expert_model_ids") or [e["model_id"] for e in (build or {}).get("experts", [])]
    is_local = config.get("expert_is_local") or [not _is_hub_id(m) for m in model_ids]
    names = config.get("expert_names") or model_ids
    top_k = config.get("num_experts_per_tok", 1)
    title, how = METHODS[method]
    # Set by `mixturekit train` when it saves a trained model
    trained = bool(config.get("mixturekit_trained"))
    if method == "bts":
        trained_line = (
            "The stitch layers are trained."
            if trained
            else "**The stitch layers are not trained yet** (they start as identity projections). "
            f"Train them with `mixturekit train` (see the [MixtureKit README]({REPOSITORY}))."
        )
    elif trained:
        trained_line = "The routers are trained and stored with the weights."
    else:
        stored = any(key.endswith(".gate.weight") for key in _stored_keys(model_dir))
        trained_line = (
            "**The routers are not trained yet**"
            + ("" if stored else ": they start random at every load")
            + f". Train them with `mixturekit train` (see the [MixtureKit README]({REPOSITORY}))."
        )
    name = repo_id or os.path.basename(os.path.normpath(model_dir))

    front = {
        "library_name": "transformers",
        "pipeline_tag": "text-generation",
        "tags": ["mixturekit", "mixture-of-experts", "moe", method, "merge"],
    }
    hub_ids = sorted({m for m, local in zip(model_ids, is_local) if not local and _is_hub_id(m)})
    if hub_ids:
        front["base_model"] = hub_ids
        front["base_model_relation"] = "merge"

    def model_cell(model_id, local):
        if local or not _is_hub_id(model_id):  # never a private path
            return f"local model `{_cell(os.path.basename(os.path.normpath(model_id)))}`"
        return f"[{_cell(model_id)}](https://huggingface.co/{model_id})"

    rows = "\n".join(
        f"| {i} | {_cell(n)} | {model_cell(m, local)} |"
        for i, (n, m, local) in enumerate(zip(names, model_ids, is_local))
    )
    details = [f"- Method: {title}: {how.format(k=top_k)}."]
    if method == "btx":
        details.append(f"- Routed projections: {', '.join(f'`{p}`' for p in config.get('router_layers', []))}")
    if method == "bts":
        details.append(f"- Stitch layer every {config.get('stitch_freq', 5)} blocks (and on the last one); expert 0 is the hub.")
    else:
        details.append(f"- Experts per token: {top_k} of {config.get('num_experts', len(model_ids))}")
        details.append(f"- Load balancing weight (alpha): {config.get('alpha', 0)}")
    details.append(f"- Base architecture: `{config.get('base_model_class', '?')}`")

    sections = [
        "---\n" + yaml.safe_dump(front, sort_keys=False, allow_unicode=True) + "---",
        MARKER,
        f"# {name}",
        f"A {len(model_ids)}-expert {title} built with [MixtureKit]({REPOSITORY}) "
        "from these models:",
        "| # | Expert | Model |\n| --- | --- | --- |\n" + rows,
        "\n".join(details),
        trained_line,
        "## Usage\n\nThe model loads with transformers (4.52 or later), MixtureKit is not needed:\n\n"
        "```python\nfrom transformers import AutoModelForCausalLM, AutoTokenizer\n\n"
        f'model = AutoModelForCausalLM.from_pretrained("{name}", trust_remote_code=True)\n'
        f'tokenizer = AutoTokenizer.from_pretrained("{name}")\n```',
        "## See which expert every token uses\n\n```bash\npip install 'mixturekit[vis]'\n"
        f"mixturekit visualize {name}\n```",
    ]
    if build:
        sections.append(
            "## Rebuild it\n\n```yaml\n" + yaml.safe_dump(_redacted(build, is_local), sort_keys=False, allow_unicode=True)
            + "```\n\n```bash\nmixturekit build config.yaml\n```"
        )
    sections.append(f"## Citation\n\n```bibtex\n{CITATION}\n```")
    return "\n\n".join(sections) + "\n"


def write_model_card(model_dir, repo_id=None, overwrite=False):
    """
    This function writes the model card as README.md in the model directory and returns its
    path. A README.md written by MixtureKit is kept unless overwrite is True; any other one
    (e.g. the generic card of a trainer) is replaced.
    """
    path = os.path.join(model_dir, "README.md")
    if os.path.exists(path) and not overwrite:
        with open(path, encoding="utf-8") as f:
            if MARKER in f.read():
                return path
    with open(path, "w", encoding="utf-8") as f:
        f.write(model_card(model_dir, repo_id))
    return path


def push_to_hub(model_dir, repo_id, private=False, token=None, commit_message=None):
    """
    This function uploads a merged model to the Hugging Face Hub, with its model card
    (written if missing). The repository is created if needed.

    Parameters
    ----------
    model_dir: str
        The directory of the merged model.
    repo_id: str
        The Hub repository, e.g. "my-org/gemma-3x4b-moe".
    private: bool, default=False
        Whether a new repository is private.
    token: str, default=None
        A Hub token; the one saved by `hf auth login` by default.
    """
    from huggingface_hub import HfApi

    write_model_card(model_dir, repo_id)
    api = HfApi(token=token)
    try:
        existing = api.repo_info(repo_id)
    except Exception:  # a new repository
        existing = None
    if existing is not None and private and not getattr(existing, "private", False):
        raise ValueError(f"{repo_id} already exists and is public: it would not be made private")
    api.create_repo(repo_id, private=private, exist_ok=True)
    return api.upload_folder(
        folder_path=model_dir,
        repo_id=repo_id,
        commit_message=commit_message or "Upload a model merged with MixtureKit",
        # Training state, local paths (the build configuration is in the card, redacted)
        ignore_patterns=[
            "checkpoint-*/**", "runs/**", "*.pyc", "__pycache__/**", "training_args.bin",
            "optimizer.pt", "scheduler.pt", "*.pth", "mixturekit_config.json",
        ],
    )
